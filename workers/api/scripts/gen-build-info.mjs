#!/usr/bin/env node
/**
 * Writes src/build-info.ts with git SHA and build timestamp.
 * Run before deploy: pnpm run gen-build-info
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
let gitSha = "dev";
try {
  gitSha = execSync("git rev-parse --short HEAD", {
    cwd: root,
    encoding: "utf8",
  }).trim();
} catch {
  // Not a git repo or git unavailable
}

const builtAt = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");

const out = `// Auto-generated by scripts/gen-build-info.mjs — do not edit by hand
export const GIT_SHA = ${JSON.stringify(gitSha)};
export const BUILT_AT = ${JSON.stringify(builtAt)};
`;

writeFileSync(join(root, "src", "build-info.ts"), out, "utf8");
console.log(`build-info.ts: ${gitSha} @ ${builtAt}`);
