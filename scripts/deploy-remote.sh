#!/usr/bin/env bash
# Deploy PDC Worker to Cloudflare (D1 migrations + Worker deploy + knowledge ingest)
# Run from the repo root: pnpm deploy:remote
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
API_DIR="$ROOT/workers/api"
WEB_ENV="$ROOT/apps/web/.env.local"

# ── Read worker name from wrangler.toml ──────────────────────────────────────
WORKER_NAME=$(grep '^name' "$API_DIR/wrangler.toml" | head -1 | sed 's/name = "\(.*\)"/\1/')
DB_NAME=$(grep 'database_name' "$API_DIR/wrangler.toml" | head -1 | sed 's/.*database_name = "\(.*\)"/\1/')
VECTORIZE_INDEX=$(grep 'index_name' "$API_DIR/wrangler.toml" | head -1 | sed 's/.*index_name = "\(.*\)"/\1/')
QUEUE_NAME=$(grep '^queue = ' "$API_DIR/wrangler.toml" | head -1 | sed 's/.*queue = "\(.*\)"/\1/')
DLQ_NAME=$(grep 'dead_letter_queue' "$API_DIR/wrangler.toml" | head -1 | sed 's/.*dead_letter_queue = "\(.*\)"/\1/')

echo "==> PDC deploy: $WORKER_NAME"
echo "    D1:        $DB_NAME"
echo "    Vectorize: $VECTORIZE_INDEX"
echo ""

cd "$ROOT"
echo "==> Installing dependencies..."
pnpm install --frozen-lockfile 2>/dev/null || pnpm install

echo "==> Applying D1 migrations (remote)..."
cd "$API_DIR"
pnpm exec wrangler d1 migrations apply "$DB_NAME" --remote

echo "==> Ensuring Vectorize index exists (safe to re-run)..."
pnpm exec wrangler vectorize create "$VECTORIZE_INDEX" --dimensions=768 --metric=cosine 2>/dev/null || true

echo "==> Ensuring dead-letter queue exists: $DLQ_NAME..."
pnpm exec wrangler queues create "$DLQ_NAME" 2>/dev/null || true

echo "==> Deploying Worker..."
DEPLOY_OUTPUT=$(pnpm exec wrangler deploy 2>&1)
echo "$DEPLOY_OUTPUT"

# Extract workers.dev URL from deploy output
API_URL=$(echo "$DEPLOY_OUTPUT" | grep -oE 'https://[a-zA-Z0-9_-]+\.[a-zA-Z0-9_-]+\.workers\.dev' | head -1)
if [ -z "$API_URL" ]; then
  echo "==> Could not parse deploy URL from output."
  echo "    Set WORKER_URL manually in .env and apps/web/.env.local"
  exit 1
fi

echo "==> Health check..."
curl -s "$API_URL/health" | head -c 200
echo ""

echo "==> Ingesting knowledge into Vectorize..."
INGEST_RESULT=$(curl -s -X POST "$API_URL/admin/ingest-knowledge" \
  -H "Content-Type: application/json" \
  -d '{"confirm":"INGEST KNOWLEDGE"}')
echo "$INGEST_RESULT"

echo "==> Writing apps/web/.env.local"
cat > "$WEB_ENV" <<EOF
# Auto-generated by scripts/deploy-remote.sh
NEXT_PUBLIC_API_URL=$API_URL
EOF

echo ""
echo "✓ Done."
echo "  API:  $API_URL"
echo "  Web:  cd $ROOT && pnpm dev"
echo ""
echo "  Next steps:"
echo "    1. Add locations via Admin panel → Locations"
echo "    2. Configure AI persona via Admin panel → AI Config"
echo "    3. Add knowledge chunks via Admin panel → Knowledge"
echo "    4. Re-ingest: curl -X POST $API_URL/admin/ingest-knowledge"
echo "    5. Set Twilio secrets: see workers/api/TWILIO.md"
echo "    6. Set Telnyx secret: wrangler secret put TELNYX_WEBHOOK_PUBLIC_KEY"
